const bengaliDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯']
const toBengali = (num: number): string =>
  String(num).split('').map(d => bengaliDigits[parseInt(d, 10)]).join('')

export const ordinal = (n: number): string => {
  const bn = toBengali(n)
  if (n >= 11 && n <= 20) return bn + 'তম'
  const last = n % 10
  if (last === 1) return bn + 'ম'
  if (last === 2 || last === 3) return bn + 'য়'
  if (last === 4) return bn + 'র্থ'
  if (last === 6) return bn + 'ষ্ঠ'
  return bn + 'ম'
}

